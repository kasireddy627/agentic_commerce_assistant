def calculate_coupon_discount(coupon: Coupon, subtotal: float, category: Optional[str] = None) -> float:
    if subtotal < coupon.min_order_inr:
        return 0.0
    if coupon.applicable_categories and category and category not in coupon.applicable_categories:
        return 0.0
    if coupon.discount_type == "flat":
        return min(coupon.discount_value, subtotal)
    raw = round(subtotal * (coupon.discount_value / 100.0), 2)
    if coupon.max_discount_inr is not None:
        return min(raw, coupon.max_discount_inr, subtotal)
    return min(raw, subtotal)
